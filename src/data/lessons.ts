const makeRoots = (category: Category, items: [string, string, string, string][]): Root[] =>
  items.map(([glyph, code, hint, explanation]) => ({
    id: `${category}-${glyph}`,
    category,
    glyph,
    code,
    hint,
    explanation,
  }))

