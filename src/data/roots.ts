const seen = new Set<string>()
export const roots: Root[] = groups.flatMap(([category, code, glyphs, clue, variants = []]) => {
  const items: { glyph: string; rootCrop?: RootCrop }[] = [
    ...[...glyphs].map((glyph) => ({ glyph })),
    ...variants.map(([glyph, x, y, width = 50, height = 50]) => ({
      glyph,
      rootCrop: [x, y, width, height] as RootCrop,
    })),
  ]
  return items.flatMap(({ glyph, rootCrop }) => {
    const id = `${category}-${code}-${glyph}`
    if (seen.has(id)) return []
    seen.add(id)
    return [
      {
        id,
        category,
        glyph,
        code,
        rootCrop,
        hint: clue,
        explanation: `${clue} 這題練的是字根 ${code.toUpperCase()}，不是這個字的完整取碼。`,
      },
    ]
  })
})
